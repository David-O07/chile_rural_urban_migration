"""Urban gradients of migration: one straight line per outcome, period and geography.

    python src/models.py

    rate = b0 + b1 * position + error        ordinary least squares, HC3 standard errors

Reads the measures tables written by measures.py. Writes aggregate tables only: slopes and averages by
tenth of the continuum (reports/tables.md). No settlement's value is written.
b1 is the change in the fitted rate across a one-unit change in normalized position.
HC3 allows unequal variances between settlements, not dependence between neighbours.
"""

import numpy as np
import pandas as pd
import statsmodels.api as sm

import chim
import geography as geo
import samples as sp

OUTCOMES = ("out_rate", "in_rate")
RUNS = (("primary", "unweighted"),                  # (geography, sample)
        ("historical_boundaries", "unweighted"),
        ("primary", "no_florida_san_pedro"))
TABLES = geo.ROOT / "reports" / "tables.md"
SPARSEST = 0.1   # exploratory: cutoff chosen after seeing the averages by tenth


def fit(d: pd.DataFrame, outcome: str) -> dict:
    """One regression. Slope and intercept are proportions, not percentages."""
    r = sm.OLS(d[outcome], sm.add_constant(d["position"])).fit(cov_type="HC3", use_t=True)
    low, high = r.conf_int().loc["position"]
    return {"n": int(r.nobs), "intercept": r.params["const"], "slope": r.params["position"],
            "se": r.bse["position"], "ci_low": low, "ci_high": high,
            "p": r.pvalues["position"], "r2": r.rsquared}


def load(geography: str, sample: str) -> pd.DataFrame:
    d = pd.read_csv(geo.OUT / geography / "measures.csv")
    return sp.select(d, next(s for s in sp.SPECS if s.name == sample))


def run() -> pd.DataFrame:
    rows = []
    for geography, sample in RUNS:
        d = load(geography, sample)
        for outcome in OUTCOMES:
            for year in chim.YEARS:
                rows.append({"geography": geography, "sample": sample, "outcome": outcome,
                             "year": year, **fit(d[d.year == year], outcome)})
    return pd.DataFrame(rows)


def without_sparsest() -> pd.DataFrame:
    """Exploratory: the primary fit without the sparsest tenth. Not re-ranked."""
    d = load("primary", "unweighted")
    return pd.DataFrame([{"outcome": o, "year": y, **fit(g[g.position > SPARSEST], o)}
                         for o in OUTCOMES for y, g in d.groupby("year")])


def by_tenth(d: pd.DataFrame) -> pd.DataFrame:
    """Unweighted mean rate (%) in each tenth of the continuum, per period."""
    tenth = np.ceil(d.position * 10 - 1e-9).astype(int).rename("tenth")
    out = d.groupby([tenth, "year"])[list(OUTCOMES)].mean() * 100
    out["n"] = d.groupby([tenth, "year"]).size()
    return out


def markdown(d: pd.DataFrame) -> str:
    """Slopes in percentage points."""
    lines = ["| Outcome | Period | n | Slope | HC3 SE | 95% interval | p | R2 |",
             "|---|---|---|---|---|---|---|---|"]
    for r in d.itertuples():
        p = "<0.001" if r.p < 0.001 else f"{r.p:.3f}"
        lines.append(f"| {r.outcome} | {r.year} | {r.n} | {r.slope * 100:.1f} | {r.se * 100:.1f} | "
                     f"{r.ci_low * 100:.1f} to {r.ci_high * 100:.1f} | {p} | {r.r2:.2f} |")
    return "\n".join(lines)


def tenth_markdown(d: pd.DataFrame) -> str:
    wide = by_tenth(d)[list(OUTCOMES)].unstack("year").round(1)
    lines = ["| Tenth | " + " | ".join(f"{o} {y}" for o, y in wide.columns) + " |",
             "|---" * (wide.shape[1] + 1) + "|"]
    return "\n".join(lines + [f"| {i} | " + " | ".join(f"{v:.1f}" for v in r) + " |"
                              for i, r in zip(wide.index, wide.to_numpy())])


def main() -> None:
    parts = ["# Result tables", "Generated by `src/models.py`. Aggregate results only. "
             "The slope estimates the change in the fitted migration rate across a one-unit change in normalized settlement position, expressed in percentage points."]
    results = run()
    for (g, s), d in results.groupby(["geography", "sample"], sort=False):
        parts += [f"## {g}, {s}", markdown(d)]
    parts += ["## Exploratory, not a main result: primary without the sparsest tenth",
              "The cutoff was chosen after seeing the averages by tenth.", markdown(without_sparsest())]
    for g in ("primary", "historical_boundaries"):
        parts += [f"## {g}: mean rate (%) by tenth of the continuum (1 = sparsest)",
                  tenth_markdown(load(g, "unweighted"))]
    TABLES.write_text("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
