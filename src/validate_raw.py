"""Step 3: read-only checks on the raw CHIM files. Prints a Markdown report.

    python src/validate_raw.py > reports/local/validation_step3.md

Nothing in data/raw is modified. The report and the label audit contain CHIM-derived
information and stay in reports/local (ignored by Git) until the licence is settled.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import pyogrio

from chim import (CHIM, N, YEARS, check_against_census, label_audit, name_key as key,
                  read_flows as read_coded_flows, read_metadata, read_raw)

LOCAL = Path(__file__).resolve().parents[1] / "reports" / "local"

# Published by INE, Censo 2002: Sintesis de Resultados (2003). Independent of CHIM.
INE_TOTAL = {1992: 13_348_401, 2002: 15_116_435}
INE_AGE5PLUS = {1992: 11_895_766, 2002: 13_965_359}
INE_ABROAD_OR_UNKNOWN_RESIDENCE = {2002: 65_639}
INE_INTERREGIONAL_MIGRANTS = {1992: 698_534, 2002: 783_430}
INE_NET_LOSS_7_9_11 = {2002: -3_801}

results = []


def check(name: str, ok: bool, detail: str) -> None:
    results.append(bool(ok))
    print(f"| {'PASS' if ok else '**FAIL**'} | {name} | {detail} |")


def section(title: str) -> None:
    print(f"\n## {title}\n\n| Result | Check | Detail |\n|---|---|---|")


def main() -> int:
    flows = {y: read_raw("flows", y) for y in YEARS}
    pops = {y: read_raw("population", y) for y in YEARS}
    meta = read_metadata()
    shp = pyogrio.read_dataframe(CHIM / "gis" / "Harmonised_municipalities.shp",
                                 read_geometry=False).set_index("C_MUN")
    census = {y: shp[f"Pop_{y}"].reindex(meta.code).to_numpy() for y in YEARS}
    labels = {y: flows[y].tmhabmun.iloc[:N].tolist() for y in YEARS}
    # Rows: residence five years ago (tm5ymun). Columns: residence now (tmhabmun).
    M = {y: flows[y].freq.to_numpy().reshape(N, N) for y in YEARS}
    code_of = {key(n): c for c, n in zip(meta.code, meta.name)}

    print("# Step 3 validation report (raw CHIM data)\n")
    print("Generated by `src/validate_raw.py`. A FAIL is a finding about the data.")

    section("Structure")
    for y in YEARS:
        f = flows[y]
        check(f"{y}: complete matrix", len(f) == N * N and not f.duplicated(["tmhabmun", "tm5ymun"]).any(),
              f"{len(f):,} rows, {f.tmhabmun.nunique()} x {f.tm5ymun.nunique()}, no duplicate pairs")
        check(f"{y}: non-negative integer counts", f.freq.dtype.kind == "i" and (f.freq >= 0).all() and not f.isna().any().any(),
              f"min {f.freq.min()}, missing {int(f.isna().sum().sum())}, zero cells {(f.freq == 0).mean():.1%}")
        ordered = (f.tmhabmun.to_numpy() == np.tile(labels[y], N)).all() and \
                  (f.tm5ymun.to_numpy() == np.repeat(labels[y], N)).all()
        check(f"{y}: regular file order", ordered, "tmhabmun cycles fastest; same order on both axes")

    section("Codes and labels")
    check("Metadata: 304 unique codes and names", len(meta) == N and meta.code.is_unique and meta.name.is_unique, "")
    check("Boundary codes equal metadata codes", set(shp.index) == set(meta.code), f"{len(shp)} boundaries")
    check("Code prefixes agree with region and province",
          (shp.index.str[:2] == shp.C_REG).all() and (shp.index.str[:3] == shp.C_PROV).all(), "")
    for y in YEARS:
        same = [code_of.get(key(n)) == c for n, c in zip(labels[y], meta.code)]
        check(f"{y}: every label names the metadata municipality at its position", all(same),
              f"{N - sum(same)} labels disagree or do not match")
    for y in YEARS:
        ratio = M[y].sum(0) / census[y]
        check(f"{y}: by FILE ORDER, current residents / census population plausible",
              ((ratio > 0.65) & (ratio < 1)).all(),
              f"sd {ratio.std():.3f}, range {ratio.min():.2f}-{ratio.max():.2f}")
    pop92 = pd.Series(census[1992], meta.code)
    by_label = [(t, code_of.get(key(n))) for t, n in zip(M[1992].sum(0), labels[1992])]
    r = np.array([t / pop92[c] for t, c in by_label if c])
    check("1992: by LABEL, same ratio plausible", ((r > 0.65) & (r < 1)).all(),
          f"sd {r.std():.3f}, range {r.min():.2f}-{r.max():.2f}, {len(r)} labels matched")

    section("Direction and denominators")
    for y in YEARS:
        ago, now = M[y].sum(1), M[y].sum(0)
        p = pops[y]
        check(f"{y}: population file = sum over tm5ymun, every municipality",
              p.tm5ymun.tolist() == labels[y] and (p.freq.to_numpy() == ago).all(),
              f"equals sum over tmhabmun in {int((p.freq.to_numpy() == now).sum())} of {N}")
        s_now, s_ago = (np.log(now / census[y]).std(), np.log(ago / census[y]).std())
        check(f"{y}: tmhabmun totals track census-date population better than tm5ymun totals",
              s_now < s_ago, f"log-ratio sd {s_now:.3f} against {s_ago:.3f}")
    for a, b in ((1982, 1992), (1992, 2002)):
        ok = M[b].sum(0) > 0
        c = np.corrcoef(np.log(census[b][ok] / census[a][ok]),
                        np.log(M[b].sum(0)[ok] / M[b].sum(1)[ok]))[0, 1]
        check(f"{b}: places gaining under this direction grew {a}-{b}", c > 0.5, f"correlation {c:.2f}")
    region = meta.code.str[:2].to_numpy()
    for y in INE_INTERREGIONAL_MIGRANTS:
        across = M[y][region[:, None] != region[None, :]].sum()
        pub = INE_INTERREGIONAL_MIGRANTS[y]
        check(f"{y}: inter-regional migrants close to INE", abs(across / pub - 1) < 0.01,
              f"{across:,} against {pub:,} ({across / pub - 1:+.2%})")
    net = pd.Series(M[2002].sum(0) - M[2002].sum(1)).groupby(region).sum()
    trio = int(net[["07", "09", "11"]].sum())
    check("2002: regions 7, 9, 11 combined net sign matches INE", trio < 0,
          f"{trio:,} against INE {INE_NET_LOSS_7_9_11[2002]:,}")
    losers = int(net[["08", "13", "03", "12"]].sum())
    check("2002: regions 8, 13, 3, 12 combined lose about 41,000 as INE states",
          -45_000 < losers < -38_000, f"{losers:,}")

    section("Totals")
    for y in YEARS:
        total, stay = M[y].sum(), np.trace(M[y])
        check(f"{y}: stayers + movers = total = arrivals = departures",
              total == M[y].sum(0).sum() == M[y].sum(1).sum(),
              f"total {total:,}; same municipality {stay:,}; different {total - stay:,}")
    for y in INE_TOTAL:
        total, cens = int(M[y].sum()), int(census[y].sum())
        print(f"| info | {y}: coverage | CHIM census {cens:,}; INE census {INE_TOTAL[y]:,} "
              f"(difference {INE_TOTAL[y] - cens:,}); INE ages 5+ {INE_AGE5PLUS[y]:,}; "
              f"matrix {total:,}; ages 5+ not in matrix {INE_AGE5PLUS[y] - total:,} "
              f"({1 - total / INE_AGE5PLUS[y]:.1%}) |")
    gap = INE_TOTAL[2002] - int(census[2002].sum())
    check("2002: CHIM census excludes exactly INE's 'abroad or unknown residence'",
          gap == INE_ABROAD_OR_UNKNOWN_RESIDENCE[2002], f"{gap:,}")
    for y in YEARS:
        print(f"| info | {y}: matrix / CHIM census population | {M[y].sum() / census[y].sum():.1%} |")
    zero = [(y, labels[y][i]) for y in YEARS for i in range(N) if M[y][i, i] == 0]
    check("Every municipality has stayers in every year", not zero, f"exceptions: {zero}")
    small = ", ".join(f"{y}: {int((census[y] < 500).sum())}" for y in YEARS)
    print(f"| info | Municipalities with census population under 500 | {small} |")

    section("Positional codes")
    for y in YEARS:
        ratio = check_against_census(read_coded_flows(y), shp[f"Pop_{y}"].reindex(meta.code))
        audit = label_audit(y)
        LOCAL.mkdir(parents=True, exist_ok=True)
        audit.to_csv(LOCAL / f"label_audit_{y}.csv", index=False)
        check(f"{y}: pinned sequences, layout, origin totals and census ratios", True,
              f"ratios {ratio.min():.2f}-{ratio.max():.2f}; {int((~audit.label_agrees).sum())} "
              f"original labels disagree, kept in label_audit_{y}.csv")

    section("Denominators (no rates calculated)")
    for y in YEARS:
        row, col, cen = (pd.Series(M[y].sum(1)), pd.Series(M[y].sum(0)), pd.Series(census[y]))
        for name, r in (("column / row sum", col / row), ("column sum / census", col / cen),
                        ("row sum / census", row / cen)):
            q = r.quantile([0, 0.05, 0.5, 0.95, 1]).round(2).tolist()
            print(f"| info | {y}: {name} across 304 units | min {q[0]}, 5% {q[1]}, median {q[2]}, 95% {q[3]}, max {q[4]} |")

    print(f"\n{sum(results)} of {len(results)} checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
